const CACHE_NAME = 'lembrancas-pwa-v1';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) return caches.delete(key);
        })
      )
    )
  );
  self.clients.claim();
});

// Cache-first para thumbnails do Firebase Storage e Network-first para páginas
self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Cache agressivo para thumbnails (_thumb.webp) para carregamento instantâneo na Grade
  if (
    url.hostname.includes('firebasestorage.googleapis.com') &&
    url.pathname.includes('_thumb')
  ) {
    event.respondWith(
      caches.open(CACHE_NAME).then(async (cache) => {
        const cached = await cache.match(request);
        if (cached) return cached;
        try {
          const response = await fetch(request);
          if (response.ok) cache.put(request, response.clone());
          return response;
        } catch (_) {
          return cached;
        }
      })
    );
    return;
  }
});
